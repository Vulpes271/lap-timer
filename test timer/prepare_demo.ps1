param([string]$LocalStart = '')
$ErrorActionPreference = 'Stop'
# Windows time zone covering Ljubljana; no Internet or extra Python packages required.
$zone = [TimeZoneInfo]::FindSystemTimeZoneById('Central Europe Standard Time')
if ($LocalStart) {
    $local = [DateTime]::ParseExact($LocalStart, 'yyyy-MM-dd HH:mm', [Globalization.CultureInfo]::InvariantCulture)
    $utc = [TimeZoneInfo]::ConvertTimeToUtc([DateTime]::SpecifyKind($local, [DateTimeKind]::Unspecified), $zone)
    $start = [DateTimeOffset]$utc
} else {
    # A completed outing shortly before preparing the simulator.
    $start = [DateTimeOffset]::UtcNow.AddMinutes(-20)
}
$local = [TimeZoneInfo]::ConvertTime($start, $zone)
$startMs = $start.ToUnixTimeMilliseconds()
$sectors = @(
    @(23000,21000,24250), @(22400,20500,23880),
    @(22100,20120,23700), @(21800,20000,23500),
    @(21500,19750,23370), @(21100,19500,23200),
    @(21300,19600,23250), @(21600,19900,23540)
)
$laps = @(for ($i = 0; $i -lt $sectors.Count; $i++) {
    [ordered]@{ number = $i + 1; lapMs = [int](($sectors[$i] | Measure-Object -Sum).Sum); sectorsMs = $sectors[$i] }
})
$summary = [ordered]@{
    id = [long][Math]::Floor($startMs / 1000)
    day = [int]$local.ToString('yyyyMMdd')
    number = 1
    startUtcMs = $startMs
    track = 'TEST - Pomposa'
    lapCount = $laps.Count
}
$fixture = [ordered]@{ version = 1; session = $summary; laps = $laps }
$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.Directory]::CreateDirectory((Join-Path $PSScriptRoot 'include')) | Out-Null
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'demo-session.json'), ($fixture | ConvertTo-Json -Depth 8), $utf8)
$summaryJson = $summary | ConvertTo-Json -Compress
$lapsJson = ConvertTo-Json -InputObject $laps -Depth 5 -Compress
$header = @"
// Generated by prepare_demo.ps1. Do not edit independently of demo-session.json.
#pragma once
constexpr char DEMO_SESSION_JSON[] = R"json($summaryJson)json";
constexpr char DEMO_LAPS_JSON[] = R"json($lapsJson)json";
constexpr unsigned DEMO_LAP_COUNT = $($laps.Count);
constexpr unsigned DEMO_BEST_MS = 63800;
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'include/demo_data.h'), $header, $utf8)
Write-Output "Prepared one session: $($local.ToString('yyyy-MM-dd HH:mm:ss zzz')), id=$($summary.id), 8 laps, best=1:03.800"
Write-Output 'Rebuild and upload after preparing new data. Power cycles retain the same session identity.'
